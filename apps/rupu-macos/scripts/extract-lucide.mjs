// --- number formatting: deterministic, minimal-digit output -----------------------------------

function fmt(n) {
  const rounded = Math.round(n * 1e6) / 1e6;
  // Avoid "-0".
  const normalized = rounded === 0 ? 0 : rounded;
  return String(normalized);
}

function num(v, fallback = 0) {
  if (v === undefined || v === null) return fallback;
  const n = typeof v === "number" ? v : parseFloat(v);
  return Number.isFinite(n) ? n : fallback;
}

// --- primitive -> path `d` conversion ----------------------------------------------------------

function circleToPath(attrs) {
  const cx = num(attrs.cx);
  const cy = num(attrs.cy);
  const r = num(attrs.r);
  return ellipseArcsPath(cx, cy, r, r);
}

function ellipseToPath(attrs) {
  const cx = num(attrs.cx);
  const cy = num(attrs.cy);
  const rx = num(attrs.rx);
  const ry = num(attrs.ry);
  return ellipseArcsPath(cx, cy, rx, ry);
}

// Two semicircle arcs, matching the exact shape SVGPathParserTests' arc-on-circle test parses.
function ellipseArcsPath(cx, cy, rx, ry) {
  const left = `${fmt(cx - rx)} ${fmt(cy)}`;
  const right = `${fmt(cx + rx)} ${fmt(cy)}`;
  return (
    `M${left}` +
    `A${fmt(rx)} ${fmt(ry)} 0 1 0 ${right}` +
    `A${fmt(rx)} ${fmt(ry)} 0 1 0 ${left}`
  );
}

function lineToPath(attrs) {
  const x1 = num(attrs.x1);
  const y1 = num(attrs.y1);
  const x2 = num(attrs.x2);
  const y2 = num(attrs.y2);
  return `M${fmt(x1)} ${fmt(y1)}L${fmt(x2)} ${fmt(y2)}`;
}

function pointsToPath(attrs, close) {
  const nums = attrs.points
    .trim()
    .split(/[\s,]+/)
    .map(Number);
  let d = "";
  for (let i = 0; i < nums.length; i += 2) {
    d += (i === 0 ? "M" : "L") + `${fmt(nums[i])} ${fmt(nums[i + 1])}`;
  }
  if (close) d += "Z";
  return d;
}

function rectToPath(attrs) {
  const x = num(attrs.x);
  const y = num(attrs.y);
  const w = num(attrs.width);
  const h = num(attrs.height);
  let rx = attrs.rx !== undefined ? num(attrs.rx) : attrs.ry !== undefined ? num(attrs.ry) : 0;
  let ry = attrs.ry !== undefined ? num(attrs.ry) : attrs.rx !== undefined ? num(attrs.rx) : 0;
  rx = Math.min(Math.max(rx, 0), w / 2);
  ry = Math.min(Math.max(ry, 0), h / 2);

  if (rx <= 0 || ry <= 0) {
    return `M${fmt(x)} ${fmt(y)}H${fmt(x + w)}V${fmt(y + h)}H${fmt(x)}Z`;
  }

  return [
    `M${fmt(x + rx)} ${fmt(y)}`,
    `H${fmt(x + w - rx)}`,
    `A${fmt(rx)} ${fmt(ry)} 0 0 1 ${fmt(x + w)} ${fmt(y + ry)}`,
    `V${fmt(y + h - ry)}`,
    `A${fmt(rx)} ${fmt(ry)} 0 0 1 ${fmt(x + w - rx)} ${fmt(y + h)}`,
    `H${fmt(x + rx)}`,
    `A${fmt(rx)} ${fmt(ry)} 0 0 1 ${fmt(x)} ${fmt(y + h - ry)}`,
    `V${fmt(y + ry)}`,
    `A${fmt(rx)} ${fmt(ry)} 0 0 1 ${fmt(x + rx)} ${fmt(y)}`,
    "Z",
  ].join("");
}

function elementToPath([tag, attrs]) {
  switch (tag) {
    case "path":
      return attrs.d;
    case "circle":
      return circleToPath(attrs);
    case "ellipse":
      return ellipseToPath(attrs);
    case "rect":
      return rectToPath(attrs);
    case "line":
      return lineToPath(attrs);
    case "polyline":
      return pointsToPath(attrs, false);
    case "polygon":
      return pointsToPath(attrs, true);
    default:
      throw new Error(`unsupported SVG primitive: ${tag}`);
  }
}

// --- reading lucide-react's element arrays -----------------------------------------------------

// lucide-react's per-icon modules look like:
//   const Clock = createLucideIcon("Clock", [
//     ["circle", { cx: "12", cy: "12", r: "10", key: "1mglay" }],
//     ["polyline", { points: "12 6 12 12 16 14", key: "68esgv" }]
//   ]);
// We pull out just the array-literal argument text and evaluate it in isolation (not the whole
// module — no import/export machinery involved). This is trusted local content (our own pinned
// node_modules dependency), not third-party input, so a plain `Function` eval is appropriate here.
function readElements(sourceName) {
  const path = join(lucideIconsDir, `${sourceName}.js`);
  if (!existsSync(path)) {
    throw new Error(`lucide-react module not found: ${path}`);
  }
  const text = readFileSync(path, "utf8");
  const start = text.indexOf("createLucideIcon(");
  if (start === -1) {
    throw new Error(`${sourceName}.js: no createLucideIcon(...) call found`);
  }
  const arrayStart = text.indexOf("[", start);
  if (arrayStart === -1) {
    throw new Error(`${sourceName}.js: no element array found after createLucideIcon(`);
  }
  let depth = 0;
  let i = arrayStart;
  for (; i < text.length; i++) {
    if (text[i] === "[") depth++;
    else if (text[i] === "]") {
      depth--;
      if (depth === 0) {
        i++;
        break;
      }
    }
  }
  const arrayText = text.slice(arrayStart, i);
  const elements = new Function(`return (${arrayText});`)();
  if (!Array.isArray(elements) || elements.length === 0) {
    throw new Error(`${sourceName}.js: parsed element array is empty`);
  }
  return elements;
}

// --- writing output ------------------------------------------------------------------------------

mkdirSync(svgDir, { recursive: true });

const swiftLicenseHeader = `// GENERATED FILE — do not edit by hand.
// Regenerate: node apps/rupu-macos/scripts/extract-lucide.mjs
// Source: lucide-react (see Icons/svg/LICENSE-lucide.txt for the ISC license + attribution).
`;

const caseEntries = [];

for (const { enumCase, asset, source } of ICONS) {
  const elements = readElements(source);
  const dStrings = elements.map(elementToPath);

  // Standalone .svg (24x24, lucide's own stroke conventions) for visual/audit review.
  const svgPaths = dStrings.map((d) => `  <path d="${d}"/>`).join("\n");
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" ` +
    `fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">\n` +
    `${svgPaths}\n</svg>\n`;
  writeFileSync(join(svgDir, `${asset}.svg`), svg);

  const pathLiterals = dStrings.map((d) => `                ${JSON.stringify(d)},`).join("\n");
  caseEntries.push(`        case .${enumCase}:\n            return [\n${pathLiterals}\n            ]`);
}

const swiftSwitch = caseEntries.join("\n");
const swiftSource = `${swiftLicenseHeader}
/// Per-icon SVG path \`d\` strings (24×24 viewBox), one entry per original lucide element —
/// \`SVGPathParser\` parses each into a \`CGPath\`; \`Icon\` strokes them all.
public enum LucideIconData {
    public static func paths(for icon: LucideIcon) -> [String] {
        switch icon {
${swiftSwitch}
        }
    }
}
`;
writeFileSync(join(outDir, "LucideIconData.swift"), swiftSource);

