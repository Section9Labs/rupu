// Extracts the ~30 lucide icons rupu.app uses out of the web app's `lucide-react` dependency and
// writes committed, SwiftUI-consumable assets:
//
//   RupuKit/Sources/RupuDesign/Icons/svg/<asset-name>.svg   — standalone 24×24 SVGs (audit/reference)
//   RupuKit/Sources/RupuDesign/Icons/svg/LICENSE-lucide.txt — ISC license + attribution
//   RupuKit/Sources/RupuDesign/Icons/LucideIconData.swift   — generated `LucideIconData.paths(for:)`
//
// Why: SwiftUI has no raw-SVG renderer, so every primitive (`circle`/`rect`/`line`/`polyline`/
// `polygon`/`ellipse`) is converted here, JS-side, into an SVG path `d` string — Swift's
// `SVGPathParser` only ever has to understand path data (`M/L/H/V/C/S/Q/T/A/Z`), never raw shape
// primitives. Circles/rounded-rect corners become `A` (arc) commands.
//
// Regeneration: run `node apps/rupu-macos/scripts/extract-lucide.mjs` from the repo root after
// `npm ci` in crates/rupu-cp/web (needed once, to populate node_modules/lucide-react). Output is
// deterministic — same lucide-react version in, byte-identical files out (icon order fixed below,
// no timestamps, numbers formatted with a fixed rounding rule) — so re-running with no lucide-react
// version bump produces a clean `git diff`.
//
// Filename note: lucide-react 0.468.0 kept a few pre-rename icons alive as alias modules that just
// re-export a renamed file's default export (e.g. `check-circle-2.js` -> `export { default } from
// './circle-check.js'`). Where that's the case, `source` below points at the CANONICAL file (the
// one with the actual element array) rather than the alias, while `asset` and the Swift enum case
// keep OUR name — web parity is by glyph, not by lucide's current filename. Every such remap is
// listed in the icon table's comments.

